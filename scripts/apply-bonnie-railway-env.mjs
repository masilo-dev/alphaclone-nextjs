#!/usr/bin/env node
/**
 * Generate missing Bonnie/MCP/cron Railway env vars and apply to Railway.
 *
 * Usage:
 *   node scripts/apply-bonnie-railway-env.mjs
 *   RAILWAY_TOKEN=... node scripts/apply-bonnie-railway-env.mjs --apply
 *   RAILWAY_TOKEN=... node scripts/apply-bonnie-railway-env.mjs --apply --core-only
 *   RAILWAY_TOKEN=... RAILWAY_SERVICE=alphaclone-web node scripts/apply-bonnie-railway-env.mjs --apply
 *
 * Writes `.env.railway.generated` (gitignored). Never commit that file.
 */
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import path from "node:path";

const ROOT = process.cwd();
const OUT = path.join(ROOT, ".env.railway.generated");

function secret(bytes = 32) {
  return randomBytes(bytes).toString("base64url");
}

function parseEnvFile(filePath) {
  if (!existsSync(filePath)) return {};
  return Object.fromEntries(
    readFileSync(filePath, "utf8")
      .split("\n")
      .map((line) => line.trim())
      .filter((line) => line && !line.startsWith("#") && line.includes("="))
      .map((line) => {
        const i = line.indexOf("=");
        return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
      }),
  );
}

function loadExisting() {
  const merged = {};
  for (const file of [".env.local", ".env.production", ".env"]) {
    Object.assign(merged, parseEnvFile(path.join(ROOT, file)));
  }
  Object.assign(merged, parseEnvFile(OUT));
  return merged;
}

const existing = loadExisting();
const generated = {
  CRON_SECRET: existing.CRON_SECRET || secret(32),
  INTERNAL_API_KEY: existing.INTERNAL_API_KEY || existing.CRON_SECRET || secret(32),
  BONNIE_EVENT_SIGNING_SECRET: existing.BONNIE_EVENT_SIGNING_SECRET || secret(32),
  BONNIE_INTERNAL_SERVICE_TOKEN: existing.BONNIE_INTERNAL_SERVICE_TOKEN || secret(32),
};

const staticVars = {
  BONNIE_DURABLE_RUNTIME: "true",
  MCP_NOTIFY_EVERY_ACTION: "true",
  BONNIE_MAX_AGENT_TOOLS: "80",
  BONNIE_WORKER_POLL_MS: "5000",
  BONNIE_MAX_TASKS_PER_RUN: "200",
  BONNIE_MAX_PARALLEL_TASKS: "20",
  BONNIE_MAX_RETRIES: "5",
  BONNIE_MAX_GRAPH_DEPTH: "12",
  NEXT_PUBLIC_APP_URL: existing.NEXT_PUBLIC_APP_URL || "https://alphaclonesystems.com",
  SOCIAL_PUBLISH_ENABLED: existing.SOCIAL_PUBLISH_ENABLED || "true",
};

const coreOnlyKeys = [
  "BONNIE_DURABLE_RUNTIME",
  "MCP_NOTIFY_EVERY_ACTION",
  "BONNIE_EVENT_SIGNING_SECRET",
  "BONNIE_INTERNAL_SERVICE_TOKEN",
];

const allVars = { ...generated, ...staticVars };
const coreOnly = process.argv.includes("--core-only");
const varsToApply = coreOnly
  ? Object.fromEntries(coreOnlyKeys.map((key) => [key, allVars[key]]))
  : allVars;

const lines = [
  "# Generated by scripts/apply-bonnie-railway-env.mjs — DO NOT COMMIT",
  `# Generated at ${new Date().toISOString()}`,
  "",
  "# ── Cron auth (use SAME Bearer on every Railway cron job) ──",
  `CRON_SECRET=${allVars.CRON_SECRET}`,
  `INTERNAL_API_KEY=${allVars.INTERNAL_API_KEY}`,
  "",
  "# ── Bonnie durable runtime ──",
  `BONNIE_DURABLE_RUNTIME=${allVars.BONNIE_DURABLE_RUNTIME}`,
  `BONNIE_EVENT_SIGNING_SECRET=${allVars.BONNIE_EVENT_SIGNING_SECRET}`,
  `BONNIE_INTERNAL_SERVICE_TOKEN=${allVars.BONNIE_INTERNAL_SERVICE_TOKEN}`,
  `BONNIE_MAX_AGENT_TOOLS=${allVars.BONNIE_MAX_AGENT_TOOLS}`,
  `BONNIE_WORKER_POLL_MS=${allVars.BONNIE_WORKER_POLL_MS}`,
  `BONNIE_MAX_TASKS_PER_RUN=${allVars.BONNIE_MAX_TASKS_PER_RUN}`,
  `BONNIE_MAX_PARALLEL_TASKS=${allVars.BONNIE_MAX_PARALLEL_TASKS}`,
  `BONNIE_MAX_RETRIES=${allVars.BONNIE_MAX_RETRIES}`,
  `BONNIE_MAX_GRAPH_DEPTH=${allVars.BONNIE_MAX_GRAPH_DEPTH}`,
  "",
  "# ── MCP notifications + social ──",
  `MCP_NOTIFY_EVERY_ACTION=${allVars.MCP_NOTIFY_EVERY_ACTION}`,
  `SOCIAL_PUBLISH_ENABLED=${allVars.SOCIAL_PUBLISH_ENABLED}`,
  "",
  "# ── App URL ──",
  `NEXT_PUBLIC_APP_URL=${allVars.NEXT_PUBLIC_APP_URL}`,
  "",
  "# Railway cron header (paste into each cron job):",
  `# Authorization: Bearer ${allVars.CRON_SECRET}`,
  "",
];

writeFileSync(OUT, lines.join("\n"), { mode: 0o600 });
console.log(`Wrote ${OUT}`);

const apply = process.argv.includes("--apply");
if (!apply) {
  console.log("\nDry run only. To push to Railway:");
  console.log("  railway login");
  console.log("  RAILWAY_TOKEN=... node scripts/apply-bonnie-railway-env.mjs --apply");
  console.log("\nOr paste variables from .env.railway.generated into Railway → alphaclone-web → Variables");
  process.exit(0);
}

function applyToService(service) {
  for (const [key, value] of Object.entries(varsToApply)) {
    const result = spawnSync(
      "railway",
      ["variable", "set", `${key}=${value}`, "--service", service],
      { stdio: "inherit", env: process.env },
    );
    if (result.status !== 0) {
      process.exit(result.status ?? 1);
    }
  }
}

if (!process.env.RAILWAY_TOKEN) {
  const whoami = spawnSync("railway", ["whoami"], { encoding: "utf8" });
  if (whoami.status !== 0) {
    console.error("\nNot logged in to Railway. Paste these into Railway dashboard:\n");
    for (const [key, value] of Object.entries(varsToApply)) {
      console.error(`${key}=${value}`);
    }
    if (!coreOnly) {
      console.error(`\nCron header: Authorization: Bearer ${allVars.CRON_SECRET}`);
    }
    console.error("\nThen: railway login && node scripts/apply-bonnie-railway-env.mjs --apply --core-only");
    process.exit(2);
  }
}

const services = (process.env.RAILWAY_SERVICES || process.env.RAILWAY_SERVICE || "alphaclone-web")
  .split(",")
  .map((s) => s.trim())
  .filter(Boolean);

console.log(
  `Applying ${Object.keys(varsToApply).length} variable(s) to Railway service(s): ${services.join(", ")}`,
);
for (const service of services) {
  console.log(`\n→ ${service}`);
  applyToService(service);
}

console.log("\nDone. Redeploy affected services.");
if (!coreOnly) {
  console.log(`Cron Bearer header: Authorization: Bearer ${allVars.CRON_SECRET}`);
}
